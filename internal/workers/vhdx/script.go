package vhdx

import (
	"fmt"
	"path/filepath"
	"strings"

	"github.com/owner/back-ez/internal/protocol"
)

// ExecutionStep represents a single actionable step in the plan.
type ExecutionStep struct {
	Order       int    `json:"order"`
	Category    string `json:"category"` // "BACKUP", "DISKPART", "BCD", "FILE"
	Command     string `json:"command"`
	Description string `json:"description"`
}

// ExecutionPlan encapsulates all diskpart and bcdedit operations for a restore point change.
type ExecutionPlan struct {
	Action         string          `json:"action"` // "CREATE", "SWITCH", "DELETE"
	TargetPointID  string          `json:"target_point_id"`
	BackupBCDPath  string          `json:"backup_bcd_path,omitempty"`
	DiskpartScript string          `json:"diskpart_script,omitempty"`
	Steps          []ExecutionStep `json:"steps"`
	GeneratedAt    string          `json:"generated_at"`
}

// BatchScript generates a runnable Windows batch (.cmd) script for the execution plan.
func (p *ExecutionPlan) BatchScript() string {
	var sb strings.Builder
	sb.WriteString("@echo off\r\n")
	sb.WriteString("rem ====================================================\r\n")
	sb.WriteString(fmt.Sprintf("rem back-EZ VHDX Execution Plan: %s (Target: %s)\r\n", p.Action, p.TargetPointID))
	sb.WriteString("rem Auto-generated by back-EZ differential engine\r\n")
	sb.WriteString("rem ====================================================\r\n")
	sb.WriteString("setlocal enabledelayedexpansion\r\n\r\n")

	for _, step := range p.Steps {
		sb.WriteString(fmt.Sprintf("rem Step %d [%s]: %s\r\n", step.Order, step.Category, step.Description))
		sb.WriteString(fmt.Sprintf("%s\r\n", step.Command))
		sb.WriteString("if %ERRORLEVEL% neq 0 (\r\n")
		sb.WriteString(fmt.Sprintf("    echo [ERROR] Step %d failed with code %%ERRORLEVEL%%\r\n", step.Order))
		if p.BackupBCDPath != "" && step.Category == "BCD" {
			sb.WriteString(fmt.Sprintf("    echo [ROLLBACK] Restoring BCD from %s\r\n", p.BackupBCDPath))
			sb.WriteString(fmt.Sprintf("    bcdedit /import \"%s\"\r\n", p.BackupBCDPath))
		}
		sb.WriteString("    exit /b %ERRORLEVEL%\r\n")
		sb.WriteString(")\r\n\r\n")
	}

	sb.WriteString("echo [SUCCESS] Execution plan completed successfully.\r\n")
	return sb.String()
}

// resolvePaths returns:
// 1. diskpartPath: e.g. `\\?\Volume{...}\EZRestore\diff.vhdx` or `C:\EZRestore\diff.vhdx`
// 2. bcdPath: e.g. `vhd=[\\?\Volume{...}]\EZRestore\diff.vhdx` or `vhd=[C:]\EZRestore\diff.vhdx`
func (e *Engine) resolvePaths(vhdxFile string) (diskpartPath string, bcdPath string) {
	relFile := strings.TrimPrefix(filepath.Clean(vhdxFile), "\\")
	relFile = strings.TrimPrefix(relFile, "/")

	if e.cfg.VolumeGUID != "" {
		vol := strings.TrimSuffix(e.cfg.VolumeGUID, "\\")
		vol = strings.TrimSuffix(vol, "/")

		diskpartPath = fmt.Sprintf("%s\\%s\\%s", vol, e.cfg.ReserveRoot, relFile)
		bcdPath = fmt.Sprintf("vhd=[%s]\\%s\\%s", vol, e.cfg.ReserveRoot, relFile)
	} else {
		// Fallback for mock/test without volume GUID
		diskpartPath = fmt.Sprintf("C:\\%s\\%s", e.cfg.ReserveRoot, relFile)
		bcdPath = fmt.Sprintf("vhd=[C:]\\%s\\%s", e.cfg.ReserveRoot, relFile)
	}
	return diskpartPath, bcdPath
}

func (e *Engine) generateCreatePlan(parent, child *protocol.RestorePoint) *ExecutionPlan {
	parentDiskpart, _ := e.resolvePaths(parent.VHDXFile)
	childDiskpart, childBCD := e.resolvePaths(child.VHDXFile)

	backupBCDPath := fmt.Sprintf("C:\\%s\\bcd_backup_%s.bcd", e.cfg.ReserveRoot, child.PointID)
	if e.cfg.VolumeGUID != "" {
		vol := strings.TrimSuffix(e.cfg.VolumeGUID, "\\")
		backupBCDPath = fmt.Sprintf("%s\\%s\\bcd_backup_%s.bcd", vol, e.cfg.ReserveRoot, child.PointID)
	}

	diskpartScript := fmt.Sprintf("create vdisk file=\"%s\" parent=\"%s\"", childDiskpart, parentDiskpart)

	steps := []ExecutionStep{
		{
			Order:       1,
			Category:    "BACKUP",
			Command:     fmt.Sprintf("bcdedit /export \"%s\"", backupBCDPath),
			Description: fmt.Sprintf("Backup current BCD store before modification to %s", backupBCDPath),
		},
		{
			Order:       2,
			Category:    "DISKPART",
			Command:     fmt.Sprintf("diskpart /s \"create_diff_%s.txt\"", child.PointID),
			Description: fmt.Sprintf("Create differential VHDX disk child (%s) with parent (%s)", child.PointID, parent.PointID),
		},
		{
			Order:       3,
			Category:    "BCD",
			Command:     fmt.Sprintf("bcdedit /set %s device %s", e.cfg.BCDEntryID, childBCD),
			Description: fmt.Sprintf("Update BCD entry %s device to %s", e.cfg.BCDEntryID, childBCD),
		},
		{
			Order:       4,
			Category:    "BCD",
			Command:     fmt.Sprintf("bcdedit /set %s osdevice %s", e.cfg.BCDEntryID, childBCD),
			Description: fmt.Sprintf("Update BCD entry %s osdevice to %s", e.cfg.BCDEntryID, childBCD),
		},
	}

	return &ExecutionPlan{
		Action:         "CREATE",
		TargetPointID:  child.PointID,
		BackupBCDPath:  backupBCDPath,
		DiskpartScript: diskpartScript,
		Steps:          steps,
		GeneratedAt:    child.CreatedAt,
	}
}

func (e *Engine) generateSwitchPlan(target *protocol.RestorePoint) *ExecutionPlan {
	_, targetBCD := e.resolvePaths(target.VHDXFile)

	backupBCDPath := fmt.Sprintf("C:\\%s\\bcd_backup_switch_%s.bcd", e.cfg.ReserveRoot, target.PointID)
	if e.cfg.VolumeGUID != "" {
		vol := strings.TrimSuffix(e.cfg.VolumeGUID, "\\")
		backupBCDPath = fmt.Sprintf("%s\\%s\\bcd_backup_switch_%s.bcd", vol, e.cfg.ReserveRoot, target.PointID)
	}

	steps := []ExecutionStep{
		{
			Order:       1,
			Category:    "BACKUP",
			Command:     fmt.Sprintf("bcdedit /export \"%s\"", backupBCDPath),
			Description: fmt.Sprintf("Backup current BCD store before switching to %s", backupBCDPath),
		},
		{
			Order:       2,
			Category:    "BCD",
			Command:     fmt.Sprintf("bcdedit /set %s device %s", e.cfg.BCDEntryID, targetBCD),
			Description: fmt.Sprintf("Switch BCD entry %s device to %s", e.cfg.BCDEntryID, targetBCD),
		},
		{
			Order:       3,
			Category:    "BCD",
			Command:     fmt.Sprintf("bcdedit /set %s osdevice %s", e.cfg.BCDEntryID, targetBCD),
			Description: fmt.Sprintf("Switch BCD entry %s osdevice to %s", e.cfg.BCDEntryID, targetBCD),
		},
	}

	return &ExecutionPlan{
		Action:        "SWITCH",
		TargetPointID: target.PointID,
		BackupBCDPath: backupBCDPath,
		Steps:         steps,
		GeneratedAt:   target.CreatedAt,
	}
}

func (e *Engine) generateDeletePlan(target *protocol.RestorePoint) *ExecutionPlan {
	targetDiskpart, _ := e.resolvePaths(target.VHDXFile)

	steps := []ExecutionStep{
		{
			Order:       1,
			Category:    "FILE",
			Command:     fmt.Sprintf("del /f /q \"%s\"", targetDiskpart),
			Description: fmt.Sprintf("Delete differential VHDX file %s", targetDiskpart),
		},
	}

	return &ExecutionPlan{
		Action:        "DELETE",
		TargetPointID: target.PointID,
		Steps:         steps,
		GeneratedAt:   target.CreatedAt,
	}
}
